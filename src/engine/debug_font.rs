//------------[Generate font bitmap RGBA buffer]-------------------
pub fn create_font_bitmap_rgba() -> Vec<u8> {
    const TEX_WIDTH: usize = 128;
    const TEX_HEIGHT: usize = 64;
    const COLS: usize = 16;
    const GLYPH_SIZE: usize = 8;

    let mut buffer = vec![0u8; TEX_WIDTH * TEX_HEIGHT * 4];

    for (c, glyph) in GLYPH_DATA.iter().enumerate().take(128) {
        let col_idx = c % COLS;
        let row_idx = c / COLS;

        let base_x = col_idx * GLYPH_SIZE;
        let base_y = row_idx * GLYPH_SIZE;

        for (py, row_byte) in glyph.iter().enumerate().take(8) {
            for px in 0..8 {
                let is_set = (row_byte & (0x80 >> px)) != 0;
                let pixel_x = base_x + px;
                let pixel_y = base_y + py;
                let idx = (pixel_y * TEX_WIDTH + pixel_x) * 4;

                if is_set {
                    buffer[idx] = 255;
                    buffer[idx + 1] = 255;
                    buffer[idx + 2] = 255;
                    buffer[idx + 3] = 255;
                } else {
                    buffer[idx] = 0;
                    buffer[idx + 1] = 0;
                    buffer[idx + 2] = 0;
                    buffer[idx + 3] = 0;
                }
            }
        }
    }

    buffer
}
